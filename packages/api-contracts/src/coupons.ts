import { z } from "zod";

/**
 * Coupon contract shared by the tendero backend, the tendero app and the
 * customer backend.
 *
 * Two rules shape everything here:
 *
 * - S4 — a coupon carries exactly ONE type out of a closed set of four. The
 *   type is the discriminator of a union of strict objects, so an array of
 *   types, an unknown type, a missing type, or the value field of a different
 *   type is a parse failure and nothing reaches the database.
 * - S11 — the tendero and the customer never see hours or minutes. Every date
 *   in a request and in a response is a date-only `YYYY-MM-DD` string, and no
 *   response carries a timestamp meant for display.
 */

/**
 * `2x1` and `combo` are the SAME type value, not two types: a `combo` coupon
 * with one product behaves as a 2x1 and with two or more as a combo, which is
 * decided by the product count in S5. That keeps the closed set at four.
 */
export const COUPON_TYPES = [
  "free_text",
  "combo",
  "percentage",
  "fixed_amount",
] as const;
export type CouponType = (typeof COUPON_TYPES)[number];
export const couponTypeSchema = z.enum(COUPON_TYPES);

/**
 * A coupon references a product the store actually sells, and the two product
 * models the codebase already has stay distinguishable (S5): a global catalog
 * assignment (`store_catalog_products`) or a store-private product
 * (`products`). The source is part of the reference, never inferred.
 */
export const COUPON_PRODUCT_SOURCES = ["store_catalog", "store_private"] as const;
export type CouponProductSource = (typeof COUPON_PRODUCT_SOURCES)[number];
export const couponProductSourceSchema = z.enum(COUPON_PRODUCT_SOURCES);

export const COUPON_CLAIM_STATUSES = ["claimed", "redeemed"] as const;
export type CouponClaimStatus = (typeof COUPON_CLAIM_STATUSES)[number];
export const couponClaimStatusSchema = z.enum(COUPON_CLAIM_STATUSES);

/**
 * A date with no time at all (S11). `z.iso.date()` rejects `2026-11-01T00:00Z`
 * and every other datetime spelling, and it rejects impossible calendar dates
 * such as `2026-02-30`. Date-only strings also compare correctly with `<=`,
 * which is what the validity-range check below relies on.
 */
export const couponDateSchema = z.iso.date();

export const couponStockSchema = z.number().int().nonnegative();

/** Whole percents only; a "20.5 % off" coupon is not a product requirement. */
export const couponPercentageSchema = z.number().int().min(1).max(100);

export const couponAmountSchema = z
  .number()
  .positive()
  .refine(
    (value) => Number(value.toFixed(2)) === value,
    "A fixed amount supports at most two decimal places.",
  );

export const couponTitleSchema = z.string().trim().min(1).max(120);
export const couponFreeTextSchema = z.string().trim().min(1).max(280);

/**
 * The object key of the coupon image, generated by the backend under the
 * `coupons` image scope. The client never chooses a key; it only echoes back
 * the one the upload ticket issued.
 */
export const couponImageObjectKeySchema = z.string().trim().min(1).max(512);

export const couponProductRefSchema = z.strictObject({
  source: couponProductSourceSchema,
  productId: z.uuid(),
});
export type CouponProductRef = z.infer<typeof couponProductRefSchema>;

const DUPLICATE_PRODUCT_MESSAGE =
  "A coupon cannot reference the same product twice.";

/**
 * The same product id under the two different sources is two different
 * products, so the identity of a reference is the pair.
 */
function hasNoDuplicateProduct(products: CouponProductRef[]): boolean {
  const seen = new Set(
    products.map((product) => `${product.source}:${product.productId}`),
  );
  return seen.size === products.length;
}

/**
 * S5 — free text, percentage discount and fixed amount link EXACTLY one store
 * product. `length(1)` makes a duplicate impossible by construction.
 */
const singleProductListSchema = z
  .array(couponProductRefSchema)
  .length(1, "This coupon type links exactly one product.");

/**
 * S5 — a `2x1 / combo` coupon links one product (then it is a 2x1) or two or
 * more (then it is a combo), and never zero.
 */
const comboProductListSchema = z
  .array(couponProductRefSchema)
  .min(1, "A 2x1 / combo coupon links at least one product.")
  .refine(hasNoDuplicateProduct, DUPLICATE_PRODUCT_MESSAGE);

const couponCreateBaseFields = {
  title: couponTitleSchema,
  description: z.string().trim().min(1).max(500).nullable().optional(),
  validFrom: couponDateSchema,
  validTo: couponDateSchema,
  totalStock: couponStockSchema,
  paused: z.boolean().default(false),
  imageObjectKey: couponImageObjectKeySchema.nullable().optional(),
};

const VALIDITY_ORDER_MESSAGE =
  "The validity must start on or before it ends (valid_from <= valid_to).";

function hasOrderedValidity(payload: {
  validFrom?: string;
  validTo?: string;
}): boolean {
  if (payload.validFrom === undefined || payload.validTo === undefined) {
    return true;
  }
  return payload.validFrom <= payload.validTo;
}

export const couponCreateSchema = z
  .discriminatedUnion("type", [
    z.strictObject({
      ...couponCreateBaseFields,
      type: z.literal("free_text"),
      freeText: couponFreeTextSchema,
      products: singleProductListSchema,
    }),
    z.strictObject({
      ...couponCreateBaseFields,
      type: z.literal("combo"),
      products: comboProductListSchema,
    }),
    z.strictObject({
      ...couponCreateBaseFields,
      type: z.literal("percentage"),
      percentageValue: couponPercentageSchema,
      products: singleProductListSchema,
    }),
    z.strictObject({
      ...couponCreateBaseFields,
      type: z.literal("fixed_amount"),
      fixedAmountValue: couponAmountSchema,
      products: singleProductListSchema,
    }),
  ])
  .refine(hasOrderedValidity, VALIDITY_ORDER_MESSAGE);
export type CouponCreateRequest = z.infer<typeof couponCreateSchema>;

const couponUpdateBaseFields = {
  title: couponTitleSchema.optional(),
  description: z.string().trim().min(1).max(500).nullable().optional(),
  validFrom: couponDateSchema.optional(),
  validTo: couponDateSchema.optional(),
  totalStock: couponStockSchema.optional(),
  paused: z.boolean().optional(),
  imageObjectKey: couponImageObjectKeySchema.nullable().optional(),
};

/**
 * An update restates the coupon's `type`. The type is NOT mutable in the MVP:
 * it travels so this contract still knows which value field and which product
 * cardinality apply, and the repository (T4) rejects an update whose type does
 * not match the stored coupon.
 *
 * Enforcement split for S5: the cardinality that depends only on the payload
 * lives here; "every product belongs to the owning store" needs a database
 * read and is enforced in the repository in T4.
 */
export const couponUpdateSchema = z
  .discriminatedUnion("type", [
    z.strictObject({
      ...couponUpdateBaseFields,
      type: z.literal("free_text"),
      freeText: couponFreeTextSchema.optional(),
      products: singleProductListSchema.optional(),
    }),
    z.strictObject({
      ...couponUpdateBaseFields,
      type: z.literal("combo"),
      products: comboProductListSchema.optional(),
    }),
    z.strictObject({
      ...couponUpdateBaseFields,
      type: z.literal("percentage"),
      percentageValue: couponPercentageSchema.optional(),
      products: singleProductListSchema.optional(),
    }),
    z.strictObject({
      ...couponUpdateBaseFields,
      type: z.literal("fixed_amount"),
      fixedAmountValue: couponAmountSchema.optional(),
      products: singleProductListSchema.optional(),
    }),
  ])
  .refine(
    (payload) =>
      Object.entries(payload).some(
        ([field, value]) => field !== "type" && value !== undefined,
      ),
    "At least one coupon field is required besides the type.",
  )
  .refine(hasOrderedValidity, VALIDITY_ORDER_MESSAGE);
export type CouponUpdateRequest = z.infer<typeof couponUpdateSchema>;

/**
 * Setting a coupon's image reference. The key is the one an upload ticket for
 * the `coupons` scope issued; the backend re-checks that it lives under the
 * owning store's own prefix before storing it.
 */
export const couponImageSetSchema = z.strictObject({
  objectKey: couponImageObjectKeySchema,
});
export type CouponImageSetRequest = z.infer<typeof couponImageSetSchema>;

/**
 * The token the tendero's scanner read out of the customer's QR (S3).
 *
 * The shape is deliberately loose: anything that is not a live token has to
 * read as "no claim matches", so the stored hash is the only authority on
 * whether a scan means something. A charset or length rule here would turn a
 * scan of some other QR into a different answer than a scan of an expired
 * Savanhi one, which is a distinction the tendero at the counter cannot act on.
 */
export const couponQrTokenSchema = z.string().trim().min(1).max(512);

/**
 * Redeeming, and previewing a redemption, both carry the scanned token in the
 * BODY of a POST. The token is a bearer secret, so it must never travel in a
 * path or a query string, which access logs and browser history keep — which is
 * also why the side-effect-free preview is a POST rather than a GET.
 */
export const couponRedemptionRequestSchema = z.strictObject({
  qrToken: couponQrTokenSchema,
});
export type CouponRedemptionRequest = z.infer<
  typeof couponRedemptionRequestSchema
>;

/**
 * What the tendero's confirmation screen shows after a scan: the coupon with
 * its type, its value and its products (each with the category the app maps an
 * icon from, S10), the store the claim belongs to, and who is standing at the
 * counter.
 *
 * `status` is the claim's state AFTER the call, so it is `redeemed` from the
 * redeem route and `claimed` from the preview, whose `redeemedOn` is null
 * because nothing was written.
 *
 * `customerName` is the customer's FIRST name and nothing else — the surname is
 * withheld, the email never travels, and `null` means the customer has not
 * completed a profile yet, so the app supplies its own wording (S11 also keeps
 * `claimId` out of what any screen renders).
 */
export type CouponRedemption = {
  claimId: string;
  status: CouponClaimStatus;
  /** Date-only, and null until the claim is actually redeemed (S11). */
  redeemedOn: string | null;
  customerName: string | null;
  coupon: Coupon;
  store: CustomerClaimStore;
};

export type CouponRedemptionResponse = {
  data: CouponRedemption;
};

/**
 * Tendero metrics (S9). Three facts the owning tendero reads about their own
 * store: the claim/redemption funnel per coupon, how many customers follow the
 * store, and the history of redemptions.
 *
 * The funnel has exactly one subtlety, and it is a product rule rather than an
 * implementation detail: claiming and redeeming are two separate moments (S8),
 * and the validity end date is the hard limit on the second one (S6). So a
 * claim that was never redeemed and is now past that date counts as CLAIMED and
 * never as redeemed — it stays in `claimedCount`, it is absent from
 * `redeemedCount`, and it never appears in the redemption history. Nothing
 * moves it anywhere later; the number of claims a coupon collected is a fact
 * about the past.
 *
 * `redeemedCount <= claimedCount` therefore always holds, and the difference is
 * the coupons customers took and did not use.
 */
export type CouponMetrics = {
  /** Lets the app open the coupon; never rendered (S11). */
  couponId: string;
  title: string;
  type: CouponType;
  totalStock: number;
  /** Claims this coupon collected, redeemed or not. */
  claimedCount: number;
  /** Claims that were actually redeemed in the store. */
  redeemedCount: number;
  /** What is left to claim; zero means the coupon is exhausted. */
  remainingStock: number;
};

/**
 * The store-wide figures of the same response, summed from its own `coupons`
 * array rather than queried separately, so the summary and the per-coupon rows
 * can never disagree.
 */
export type StoreMetricsTotals = {
  couponCount: number;
  claimedCount: number;
  redeemedCount: number;
  remainingStock: number;
};

/**
 * One line of the redemption history: which coupon was redeemed, who stood at
 * the counter, and on which day.
 *
 * `customerName` is the customer's FIRST name and nothing else — the surname is
 * withheld and the email never travels, exactly as in `CouponRedemption` — and
 * it is null when the customer never completed a profile, so the app supplies
 * its own wording. `redeemedOn` is date-only: the schema stores no redemption
 * time at all, so no screen can render one (S11).
 */
export type CouponRedemptionHistoryEntry = {
  /** A stable list key; never rendered (S11). */
  claimId: string;
  couponTitle: string;
  customerName: string | null;
  redeemedOn: string;
};

/**
 * Redemption history grows for the life of a store, so it is never returned
 * whole: one page comes back with the window it was read through, and
 * `nextOffset` is the offset of the next page or null when this was the last
 * one. It is derived by reading one row past the limit, so a client never pays
 * for a `count(*)` over the whole history to learn there is nothing more.
 */
export type CouponRedemptionHistoryPage = {
  entries: CouponRedemptionHistoryEntry[];
  limit: number;
  offset: number;
  nextOffset: number | null;
};

/** The default page of history when the caller asks for no particular one. */
export const REDEMPTION_HISTORY_DEFAULT_LIMIT = 20;

/**
 * The hard ceiling on one page. A caller asking for more is REJECTED rather
 * than silently clamped: a client that believes it read 500 entries and
 * received 100 would page incorrectly from then on.
 */
export const REDEMPTION_HISTORY_MAX_LIMIT = 100;

/**
 * The page window, as it arrives in a query string — hence the coercion, and
 * hence the explicit finite and integer checks: `Number("")` is `0`, so a blank
 * `limit=` would otherwise read as a request for no rows at all.
 */
export const redemptionHistoryQuerySchema = z.strictObject({
  limit: z.coerce
    .number()
    .refine(Number.isFinite, "The limit must be a number.")
    .int()
    .min(1)
    .max(REDEMPTION_HISTORY_MAX_LIMIT)
    .default(REDEMPTION_HISTORY_DEFAULT_LIMIT),
  offset: z.coerce
    .number()
    .refine(Number.isFinite, "The offset must be a number.")
    .int()
    .min(0)
    .default(0),
});
export type RedemptionHistoryQuery = z.infer<
  typeof redemptionHistoryQuerySchema
>;

/**
 * How many redemptions the metrics summary carries inline. It is a preview for
 * the tendero's home tab, not the history itself: the dedicated history route
 * is where paging happens.
 */
export const STORE_METRICS_RECENT_REDEMPTIONS = 5;

/**
 * Everything the tendero's home tab shows about one of their stores, in ONE
 * response (S9): the follower count, the per-coupon funnel, the store-wide
 * totals and the newest redemptions. The tab therefore costs one request, and
 * the dedicated history route exists for the screen that pages through it.
 *
 * `storeId` is here so a client holding several stores can tell the responses
 * apart; it is never rendered (S11).
 */
export type StoreMetrics = {
  storeId: string;
  followersCount: number;
  totals: StoreMetricsTotals;
  coupons: CouponMetrics[];
  recentRedemptions: CouponRedemptionHistoryEntry[];
};

export type StoreMetricsResponse = {
  data: StoreMetrics;
};

export type CouponRedemptionHistoryResponse = {
  data: CouponRedemptionHistoryPage;
};

/** Follow and unfollow both identify the store and nothing else (S7). */
export const storeFollowSchema = z.strictObject({ storeId: z.uuid() });
export type StoreFollowRequest = z.infer<typeof storeFollowSchema>;

/**
 * The fixed discovery radius (L6: “radio fijo de 3km”). It lives in the
 * contract because the customer app shows the same radius on its map that the
 * feed filters by; two copies of 3 km would drift.
 */
export const COUPON_FEED_RADIUS_METERS = 3_000;

/**
 * A coordinate as it arrives in a query string: an optional sign, digits, and
 * an optional fraction. Nothing else.
 *
 * The shape is matched BEFORE anything is converted, because `Number` is far
 * too generous to be a validator here: `Number("")`, `Number("  ")` and
 * `Number("+")` are all `0`, so a blank `lat=` would read as the equator and
 * the feed would answer from 0,0 as if the customer were standing in the
 * Atlantic. `Number` also accepts spellings that are not positions —
 * `"0x10"` is 16 and `"1e1"` is 10 — and a finite check cannot tell any of
 * them apart from a real reading, since every one of them IS finite.
 */
const DECIMAL_COORDINATE = /^[+-]?\d+(\.\d+)?$/;

/**
 * The customer's own position. Both axes parse the same way and differ only in
 * their range, so the bound is the parameter.
 */
const coordinateSchema = (bound: 90 | 180, axis: "Latitude" | "Longitude") =>
  z
    .string(`${axis} must be a decimal number.`)
    .regex(DECIMAL_COORDINATE, `${axis} must be a decimal number.`)
    .transform(Number)
    .pipe(z.number().min(-bound).max(bound));

export const customerCoordinatesSchema = z.strictObject({
  lat: coordinateSchema(90, "Latitude"),
  lng: coordinateSchema(180, "Longitude"),
});
export type CustomerCoordinates = z.infer<typeof customerCoordinatesSchema>;

/**
 * The feed's query string (C3). The customer may deny the location permission,
 * and the decision was “Seguidas + pedir permiso”: with no coordinates at all
 * the feed answers the followed half of the one feed instead of nothing.
 *
 * The pair is all-or-nothing. Half a position is NOT a position — a lone `lat`
 * would otherwise have to be paired with an invented longitude — so exactly one
 * axis is rejected. `.optional()` admits only an ABSENT parameter, so every
 * spelling L13 banned (a blank, a space, a lone sign, hex, an exponent) is
 * still rejected by the grammar above rather than read as the equator.
 */
export const customerFeedQuerySchema = z
  .strictObject({
    lat: coordinateSchema(90, "Latitude").optional(),
    lng: coordinateSchema(180, "Longitude").optional(),
  })
  .refine(
    (query) => (query.lat === undefined) === (query.lng === undefined),
    "Latitude and longitude travel together.",
  );
export type CustomerFeedQuery = z.infer<typeof customerFeedQuerySchema>;

/**
 * A store as a customer sees it (S11): no `createdAt`, so no screen can render
 * a time. This is deliberately NOT the tendero-facing `Store`, which carries
 * the owner id, the bank account fields and a creation timestamp — none of
 * which belong in a customer response.
 *
 * `latitude`/`longitude` are nullable because the column is: a tendero can
 * finish onboarding without pinning the store on the map.
 */
export type CustomerStore = {
  id: string;
  name: string;
  address: string | null;
  latitude: number | null;
  longitude: number | null;
};

/**
 * A store inside the radius. Its coordinates are non-null by construction — a
 * store with no coordinates has no distance and can never be “within 3 km”.
 *
 * The distance travels twice because S11 forbids rendering an id but says
 * nothing about units: a card shows `distanceKm` when it is at least one
 * kilometre and `distanceMeters` when it is closer, and neither client has to
 * re-derive one from the other.
 */
export type NearbyStore = CustomerStore & {
  latitude: number;
  longitude: number;
  distanceMeters: number;
  distanceKm: number;
};

/**
 * The store of a feed item. The distance is nullable here and not on
 * `NearbyStore`, because a followed store always appears in the feed (L7)
 * including when it has no coordinates to measure from.
 */
export type CustomerFeedStore = CustomerStore & {
  distanceMeters: number | null;
  distanceKm: number | null;
};

/**
 * One entry of the SINGLE feed (S7). `followed` drives the “Siguiendo” badge
 * and `claimed` tells the card whether this customer already holds a claim, so
 * one screen renders nearby and followed coupons without a second request.
 */
export type CustomerCouponFeedItem = {
  coupon: Coupon;
  store: CustomerFeedStore;
  followed: boolean;
  claimed: boolean;
};

/**
 * What a customer's claim looks like in the wallet.
 *
 * `expired` is DERIVED on read and never stored: S6 makes the validity end
 * date the hard limit, so an unredeemed claim past `validTo` is expired no
 * matter what the row says. The stored status stays `claimed`, which is what
 * keeps the rule in one place instead of in a nightly job.
 *
 * `released` is derived the same way (C4): the customer gave the coupon back,
 * so the row stays `claimed` and carries a `released_on` date. It is SHOWN
 * rather than hidden — a claim that silently disappears reads as a bug to the
 * person who released it, and the re-claim refusal would have nothing to point
 * at. `released` wins over `expired`: the release is why the claim ended.
 */
export const CUSTOMER_CLAIM_STATUSES = [
  "claimed",
  "redeemed",
  "expired",
  "released",
] as const;
export type CustomerClaimStatus = (typeof CUSTOMER_CLAIM_STATUSES)[number];

/** The store a claim is redeemable at; the customer reads the name, not the id. */
export type CustomerClaimStore = {
  id: string;
  name: string;
};

/**
 * A claim as its owner sees it: the coupon it applies to, where to redeem it,
 * and the derived status. `qrToken` is the plaintext token and is non-null
 * EXACTLY in the two responses that issue one — the claim itself and a
 * re-issue — because only its hash is stored (S3).
 */
export type CustomerClaim = {
  id: string;
  status: CustomerClaimStatus;
  qrToken: string | null;
  claimedOn: string;
  redeemedOn: string | null;
  coupon: Coupon;
  store: CustomerClaimStore;
};

/**
 * The category a coupon's product belongs to, carried so the app can pick a
 * per-category icon instead of a per-product image (S10): the MVP has no
 * product images at all.
 *
 * `key` is the stable value to map an icon from — the catalog category's slug.
 * A store-authored category has no slug (its name is free text the tendero
 * typed), so `key` is null there and the app falls back to a default icon.
 * `name` is for display; `id` is never rendered (S11).
 */
export type CouponProductCategory = {
  id: string;
  name: string;
  key: string | null;
};

/**
 * A coupon's product reference as the clients see it: the reference itself plus
 * the data a list row needs, so the UI never has to fetch the catalog to render
 * a coupon. `name` is the store-private product's name or the catalog product's
 * commercial name, depending on the source.
 *
 * `category` is null as a whole when the product has none, rather than an id
 * with a missing name. A store-private product resolves its store-authored
 * category first and its catalog category second, matching what the products
 * repository already reads (`storeCategoryId ?? categoryId`).
 *
 * There is NO product image field: the MVP renders the coupon's own photo, and
 * this category icon when the coupon has no photo (S10).
 */
export type CouponProductDetail = CouponProductRef & {
  name: string;
  category: CouponProductCategory | null;
};

/**
 * A coupon as the clients see it. `validFrom`/`validTo` are date-only and there
 * is no creation timestamp, so no screen can render a time (S11). `id` and
 * `storeId` exist for later mutations and are never displayed.
 *
 * Exactly one of `freeText`, `percentageValue` and `fixedAmountValue` is
 * non-null, matching the coupon's `type` (S4).
 */
export type Coupon = {
  id: string;
  storeId: string;
  type: CouponType;
  title: string;
  description: string | null;
  freeText: string | null;
  percentageValue: number | null;
  fixedAmountValue: number | null;
  validFrom: string;
  validTo: string;
  totalStock: number;
  /** Claims already reserved against the stock (S8). */
  claimedCount: number;
  /** `totalStock - claimedCount`; zero means the coupon is exhausted. */
  remainingStock: number;
  paused: boolean;
  imageUrl: string | null;
  products: CouponProductDetail[];
};

/**
 * A claim as the customer sees it.
 *
 * `qrToken` is the opaque high-entropy token the customer renders as a QR for
 * the tendero to scan (S3). Only its hash is persisted, so the token is
 * present exactly once — in the response that issues it — and is `null`
 * everywhere else, including when a claim is listed again later.
 */
export type CouponClaim = {
  id: string;
  couponId: string;
  status: CouponClaimStatus;
  qrToken: string | null;
  claimedOn: string;
  redeemedOn: string | null;
};

