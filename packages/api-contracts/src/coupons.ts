import { z } from "zod";

/**
 * Coupon contract shared by the tendero backend, the tendero app and the
 * customer backend.
 *
 * Two rules shape everything here:
 *
 * - S4 — a coupon carries exactly ONE type out of a closed set of four. The
 *   type is the discriminator of a union of strict objects, so an array of
 *   types, an unknown type, a missing type, or the value field of a different
 *   type is a parse failure and nothing reaches the database.
 * - S11 — the tendero and the customer never see hours or minutes. Every date
 *   in a request and in a response is a date-only `YYYY-MM-DD` string, and no
 *   response carries a timestamp meant for display.
 */

/**
 * `2x1` and `combo` are the SAME type value, not two types: a `combo` coupon
 * with one product behaves as a 2x1 and with two or more as a combo, which is
 * decided by the product count in S5. That keeps the closed set at four.
 */
export const COUPON_TYPES = [
  "free_text",
  "combo",
  "percentage",
  "fixed_amount",
] as const;
export type CouponType = (typeof COUPON_TYPES)[number];
export const couponTypeSchema = z.enum(COUPON_TYPES);

/**
 * A coupon references a product the store actually sells, and the two product
 * models the codebase already has stay distinguishable (S5): a global catalog
 * assignment (`store_catalog_products`) or a store-private product
 * (`products`). The source is part of the reference, never inferred.
 */
export const COUPON_PRODUCT_SOURCES = ["store_catalog", "store_private"] as const;
export type CouponProductSource = (typeof COUPON_PRODUCT_SOURCES)[number];
export const couponProductSourceSchema = z.enum(COUPON_PRODUCT_SOURCES);

export const COUPON_CLAIM_STATUSES = ["claimed", "redeemed"] as const;
export type CouponClaimStatus = (typeof COUPON_CLAIM_STATUSES)[number];
export const couponClaimStatusSchema = z.enum(COUPON_CLAIM_STATUSES);

/**
 * A date with no time at all (S11). `z.iso.date()` rejects `2026-11-01T00:00Z`
 * and every other datetime spelling, and it rejects impossible calendar dates
 * such as `2026-02-30`. Date-only strings also compare correctly with `<=`,
 * which is what the validity-range check below relies on.
 */
export const couponDateSchema = z.iso.date();

export const couponStockSchema = z.number().int().nonnegative();

/** Whole percents only; a "20.5 % off" coupon is not a product requirement. */
export const couponPercentageSchema = z.number().int().min(1).max(100);

export const couponAmountSchema = z
  .number()
  .positive()
  .refine(
    (value) => Number(value.toFixed(2)) === value,
    "A fixed amount supports at most two decimal places.",
  );

export const couponTitleSchema = z.string().trim().min(1).max(120);
export const couponFreeTextSchema = z.string().trim().min(1).max(280);

/**
 * The object key of the coupon image, generated by the backend under the
 * `coupons` image scope. The client never chooses a key; it only echoes back
 * the one the upload ticket issued.
 */
export const couponImageObjectKeySchema = z.string().trim().min(1).max(512);

export const couponProductRefSchema = z.strictObject({
  source: couponProductSourceSchema,
  productId: z.uuid(),
});
export type CouponProductRef = z.infer<typeof couponProductRefSchema>;

const DUPLICATE_PRODUCT_MESSAGE =
  "A coupon cannot reference the same product twice.";

/**
 * The same product id under the two different sources is two different
 * products, so the identity of a reference is the pair.
 */
function hasNoDuplicateProduct(products: CouponProductRef[]): boolean {
  const seen = new Set(
    products.map((product) => `${product.source}:${product.productId}`),
  );
  return seen.size === products.length;
}

/**
 * S5 — free text, percentage discount and fixed amount link EXACTLY one store
 * product. `length(1)` makes a duplicate impossible by construction.
 */
const singleProductListSchema = z
  .array(couponProductRefSchema)
  .length(1, "This coupon type links exactly one product.");

/**
 * S5 — a `2x1 / combo` coupon links one product (then it is a 2x1) or two or
 * more (then it is a combo), and never zero.
 */
const comboProductListSchema = z
  .array(couponProductRefSchema)
  .min(1, "A 2x1 / combo coupon links at least one product.")
  .refine(hasNoDuplicateProduct, DUPLICATE_PRODUCT_MESSAGE);

const couponCreateBaseFields = {
  title: couponTitleSchema,
  description: z.string().trim().min(1).max(500).nullable().optional(),
  validFrom: couponDateSchema,
  validTo: couponDateSchema,
  totalStock: couponStockSchema,
  paused: z.boolean().default(false),
  imageObjectKey: couponImageObjectKeySchema.nullable().optional(),
};

const VALIDITY_ORDER_MESSAGE =
  "The validity must start on or before it ends (valid_from <= valid_to).";

function hasOrderedValidity(payload: {
  validFrom?: string;
  validTo?: string;
}): boolean {
  if (payload.validFrom === undefined || payload.validTo === undefined) {
    return true;
  }
  return payload.validFrom <= payload.validTo;
}

export const couponCreateSchema = z
  .discriminatedUnion("type", [
    z.strictObject({
      ...couponCreateBaseFields,
      type: z.literal("free_text"),
      freeText: couponFreeTextSchema,
      products: singleProductListSchema,
    }),
    z.strictObject({
      ...couponCreateBaseFields,
      type: z.literal("combo"),
      products: comboProductListSchema,
    }),
    z.strictObject({
      ...couponCreateBaseFields,
      type: z.literal("percentage"),
      percentageValue: couponPercentageSchema,
      products: singleProductListSchema,
    }),
    z.strictObject({
      ...couponCreateBaseFields,
      type: z.literal("fixed_amount"),
      fixedAmountValue: couponAmountSchema,
      products: singleProductListSchema,
    }),
  ])
  .refine(hasOrderedValidity, VALIDITY_ORDER_MESSAGE);
export type CouponCreateRequest = z.infer<typeof couponCreateSchema>;

const couponUpdateBaseFields = {
  title: couponTitleSchema.optional(),
  description: z.string().trim().min(1).max(500).nullable().optional(),
  validFrom: couponDateSchema.optional(),
  validTo: couponDateSchema.optional(),
  totalStock: couponStockSchema.optional(),
  paused: z.boolean().optional(),
  imageObjectKey: couponImageObjectKeySchema.nullable().optional(),
};

/**
 * An update restates the coupon's `type`. The type is NOT mutable in the MVP:
 * it travels so this contract still knows which value field and which product
 * cardinality apply, and the repository (T4) rejects an update whose type does
 * not match the stored coupon.
 *
 * Enforcement split for S5: the cardinality that depends only on the payload
 * lives here; "every product belongs to the owning store" needs a database
 * read and is enforced in the repository in T4.
 */
export const couponUpdateSchema = z
  .discriminatedUnion("type", [
    z.strictObject({
      ...couponUpdateBaseFields,
      type: z.literal("free_text"),
      freeText: couponFreeTextSchema.optional(),
      products: singleProductListSchema.optional(),
    }),
    z.strictObject({
      ...couponUpdateBaseFields,
      type: z.literal("combo"),
      products: comboProductListSchema.optional(),
    }),
    z.strictObject({
      ...couponUpdateBaseFields,
      type: z.literal("percentage"),
      percentageValue: couponPercentageSchema.optional(),
      products: singleProductListSchema.optional(),
    }),
    z.strictObject({
      ...couponUpdateBaseFields,
      type: z.literal("fixed_amount"),
      fixedAmountValue: couponAmountSchema.optional(),
      products: singleProductListSchema.optional(),
    }),
  ])
  .refine(
    (payload) =>
      Object.entries(payload).some(
        ([field, value]) => field !== "type" && value !== undefined,
      ),
    "At least one coupon field is required besides the type.",
  )
  .refine(hasOrderedValidity, VALIDITY_ORDER_MESSAGE);
export type CouponUpdateRequest = z.infer<typeof couponUpdateSchema>;

/**
 * Setting a coupon's image reference. The key is the one an upload ticket for
 * the `coupons` scope issued; the backend re-checks that it lives under the
 * owning store's own prefix before storing it.
 */
export const couponImageSetSchema = z.strictObject({
  objectKey: couponImageObjectKeySchema,
});
export type CouponImageSetRequest = z.infer<typeof couponImageSetSchema>;

/** Follow and unfollow both identify the store and nothing else (S7). */
export const storeFollowSchema = z.strictObject({ storeId: z.uuid() });
export type StoreFollowRequest = z.infer<typeof storeFollowSchema>;

/**
 * A coupon's product reference as the clients see it: the reference itself plus
 * the data a list row needs, so the UI never has to fetch the catalog to render
 * a coupon. `name` is the store-private product's name or the catalog product's
 * commercial name, depending on the source.
 *
 * `imageUrl` is forward-compatible and always `null` today: neither
 * `catalog_products` nor `products` carries an image column, so there is no
 * product image to serve yet. The coupon's own `imageUrl` is what the UI
 * renders in the meantime.
 */
export type CouponProductDetail = CouponProductRef & {
  name: string;
  imageUrl: string | null;
};

/**
 * A coupon as the clients see it. `validFrom`/`validTo` are date-only and there
 * is no creation timestamp, so no screen can render a time (S11). `id` and
 * `storeId` exist for later mutations and are never displayed.
 *
 * Exactly one of `freeText`, `percentageValue` and `fixedAmountValue` is
 * non-null, matching the coupon's `type` (S4).
 */
export type Coupon = {
  id: string;
  storeId: string;
  type: CouponType;
  title: string;
  description: string | null;
  freeText: string | null;
  percentageValue: number | null;
  fixedAmountValue: number | null;
  validFrom: string;
  validTo: string;
  totalStock: number;
  /** Claims already reserved against the stock (S8). */
  claimedCount: number;
  /** `totalStock - claimedCount`; zero means the coupon is exhausted. */
  remainingStock: number;
  paused: boolean;
  imageUrl: string | null;
  products: CouponProductDetail[];
};

/**
 * A claim as the customer sees it.
 *
 * `qrToken` is the opaque high-entropy token the customer renders as a QR for
 * the tendero to scan (S3). Only its hash is persisted, so the token is
 * present exactly once — in the response that issues it — and is `null`
 * everywhere else, including when a claim is listed again later.
 */
export type CouponClaim = {
  id: string;
  couponId: string;
  status: CouponClaimStatus;
  qrToken: string | null;
  claimedOn: string;
  redeemedOn: string | null;
};

/** Follow and unfollow are idempotent, so the response is the end state (S7). */
export type StoreFollow = {
  storeId: string;
  following: boolean;
};

export type CouponsResponse = {
  data: Coupon[];
};

export type CouponResponse = {
  data: Coupon;
};

export type CouponClaimResponse = {
  data: CouponClaim;
};

export type StoreFollowResponse = {
  data: StoreFollow;
};
