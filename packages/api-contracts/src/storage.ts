import { z } from "zod";

/**
 * Image upload contract shared by the backend and the mobile clients.
 *
 * `createBackendApp` installs `express.json({ limit: "100kb" })`, so image
 * bytes never travel through the API. The client asks for an upload ticket,
 * PUTs the bytes straight to the object store with the presigned URL, and then
 * registers the resulting object reference.
 *
 * The scope is the owning entity kind. Only `stores` exists today; coupon
 * images reuse the same ticket shape once coupons land.
 */
export const IMAGE_SCOPES = ["stores", "coupons"] as const;
export type ImageScope = (typeof IMAGE_SCOPES)[number];

export const IMAGE_CONTENT_TYPES = [
  "image/jpeg",
  "image/png",
  "image/webp",
] as const;
export type ImageContentType = (typeof IMAGE_CONTENT_TYPES)[number];

export const IMAGE_CONTENT_TYPE_EXTENSIONS: Record<ImageContentType, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
};

/**
 * 5 MiB. The presigned URL pins the exact byte count it was signed for.
 *
 * It is a literal so `MaxImageBytes` stays a literal type. The mobile clients
 * cannot import this module at runtime (Jest and Metro resolve CommonJS, and
 * this package is ESM-only), so they restate the number and annotate it with
 * `MaxImageBytes`, which makes any drift a type error instead of a silent
 * mismatch with the backend.
 */
export const MAX_IMAGE_BYTES = 5_242_880 as const;
export type MaxImageBytes = typeof MAX_IMAGE_BYTES;

export const imageContentTypeSchema = z.enum(IMAGE_CONTENT_TYPES);
export const imageByteSizeSchema = z
  .number()
  .int()
  .positive()
  .max(MAX_IMAGE_BYTES);

export const imageUploadTicketRequestSchema = z.strictObject({
  contentType: imageContentTypeSchema,
  contentLength: imageByteSizeSchema,
});
export type ImageUploadTicketRequest = z.infer<
  typeof imageUploadTicketRequestSchema
>;

export type ImageUploadTicket = {
  /** Generated by the backend. The client never chooses an object key. */
  objectKey: string;
  uploadUrl: string;
  contentType: ImageContentType;
  contentLength: number;
  expiresInSeconds: number;
};

export const storePhotoRegisterSchema = z.strictObject({
  objectKey: z.string().trim().min(1).max(512),
  contentType: imageContentTypeSchema,
  byteSize: imageByteSizeSchema,
});
export type StorePhotoRegisterRequest = z.infer<
  typeof storePhotoRegisterSchema
>;

/**
 * A store photo as the clients see it. There is no timestamp and no caption:
 * the UI only ever renders the image, so S11 ("no IDs, no times") has nothing
 * to mis-render. `id` exists for later mutations and is never displayed.
 */
export type StorePhoto = {
  id: string;
  url: string;
  contentType: ImageContentType;
  position: number;
};
